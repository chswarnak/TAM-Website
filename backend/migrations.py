"""Versioned, idempotent SQLite schema migrations.

Why Python instead of plain .sql files: the live database was patched by
hand while the gallery feature was built, so some columns may already
exist. SQLite has no "ADD COLUMN IF NOT EXISTS", so each step checks the
current schema before changing it. Every migration is safe to re-run.

Usage (from the repository root):
    python backend/migrate.py                # migrate TAM_DB_PATH (with backup)
    python backend/migrate.py --db path.db   # migrate a specific file
"""

import logging
import sqlite3
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable

logger = logging.getLogger(__name__)

MIGRATIONS_DIR = Path(__file__).resolve().parent.parent / "database" / "migrations"

SCHEMA_HEADER = (
    "-- TAM Smart Event Photo Sharing System\n"
    "-- Database schema only; no application records.\n"
    "-- GENERATED by `python backend/migrate.py --dump-schema database/schema.sql`.\n"
    "-- Do not edit by hand: add a migration in backend/migrations.py instead.\n\n"
)


def _columns(conn: sqlite3.Connection, table: str) -> set[str]:
    return {row[1] for row in conn.execute(f"PRAGMA table_info({table})")}


def _add_column(conn: sqlite3.Connection, table: str, column: str, ddl: str) -> None:
    if column not in _columns(conn, table):
        conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {ddl}")


def _m000_baseline(conn: sqlite3.Connection) -> None:
    # executescript() would commit our transaction, so run statements one by one.
    script = (MIGRATIONS_DIR / "000_baseline.sql").read_text()
    for statement in script.split(";"):
        lines = [
            line for line in statement.splitlines()
            if line.strip() and not line.strip().startswith("--")
        ]
        if lines:
            conn.execute("\n".join(lines))


def _m001_gallery(conn: sqlite3.Connection) -> None:
    _add_column(conn, "events", "gallery_enabled", "INTEGER NOT NULL DEFAULT 0")
    _add_column(conn, "photos", "gallery_approved", "INTEGER NOT NULL DEFAULT 0")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS gallery_downloads (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            event_id TEXT NOT NULL,
            media_type TEXT NOT NULL,
            media_id INTEGER NOT NULL,
            downloader_type TEXT NOT NULL,
            downloader_id TEXT NOT NULL,
            downloaded_at_utc TEXT NOT NULL
        )
    """)


def _m002_accounts(conn: sqlite3.Connection) -> None:
    # Contributors: separate login identifiers from the display name.
    _add_column(conn, "contributors", "email", "TEXT")
    _add_column(conn, "contributors", "username", "TEXT")
    _add_column(conn, "contributors", "must_change_password",
                "INTEGER NOT NULL DEFAULT 0")
    _add_column(conn, "contributors", "registered_at", "TEXT")
    added_notified = "notified_at" not in _columns(conn, "contributors")
    _add_column(conn, "contributors", "notified_at", "TEXT")
    if added_notified:
        # Existing registrations are already visible on the dashboard;
        # don't email the super admin about all of them at once.
        conn.execute(
            "UPDATE contributors SET notified_at = CURRENT_TIMESTAMP"
        )
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS ux_contributors_email "
        "ON contributors(lower(email)) WHERE email IS NOT NULL"
    )
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS ux_contributors_username "
        "ON contributors(lower(username)) WHERE username IS NOT NULL"
    )

    conn.execute("""
        CREATE TABLE IF NOT EXISTS attendees (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            event_id TEXT NOT NULL,
            full_name TEXT NOT NULL,
            email TEXT NOT NULL,
            username TEXT,
            mobile_number TEXT,
            password_hash TEXT NOT NULL,
            approved INTEGER NOT NULL DEFAULT 0,
            approved_by_admin_id INTEGER,
            approved_at TEXT,
            active INTEGER NOT NULL DEFAULT 1,
            deleted_at TEXT,
            must_change_password INTEGER NOT NULL DEFAULT 0,
            registered_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
            notified_at TEXT
        )
    """)
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS ux_attendees_email "
        "ON attendees(lower(email))"
    )
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS ux_attendees_username "
        "ON attendees(lower(username)) WHERE username IS NOT NULL"
    )

    # Signed single-use links (approval, password reset).
    conn.execute("""
        CREATE TABLE IF NOT EXISTS account_tokens (
            token_hash TEXT PRIMARY KEY,
            purpose TEXT NOT NULL CHECK (purpose IN ('approve', 'reset')),
            account_kind TEXT NOT NULL
                CHECK (account_kind IN ('contributor', 'attendee')),
            account_id INTEGER NOT NULL,
            expires_at INTEGER NOT NULL,
            used_at INTEGER
        )
    """)

    # Failed login attempts; identifiers are stored as HMACs only.
    conn.execute("""
        CREATE TABLE IF NOT EXISTS login_attempts (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            scope TEXT NOT NULL,
            key_hash TEXT NOT NULL,
            attempted_at REAL NOT NULL
        )
    """)
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_login_attempts_key "
        "ON login_attempts(scope, key_hash, attempted_at)"
    )


def _m003_attendee_search(conn: sqlite3.Connection) -> None:
    _add_column(conn, "attendee_consents", "attendee_id", "INTEGER")
    _add_column(conn, "guest_search_sessions", "attendee_id", "INTEGER")
    _add_column(conn, "guest_photo_downloads", "attendee_id", "INTEGER")


def _m004_indexing_and_notifications(conn: sqlite3.Connection) -> None:
    _add_column(conn, "events", "auto_authorize_face_indexing",
                "INTEGER NOT NULL DEFAULT 0")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS notification_state (
            name TEXT PRIMARY KEY,
            last_sent_at INTEGER NOT NULL
        )
    """)


def reconcile_indexed_photos(conn: sqlite3.Connection) -> None:
    """Make photos indexed before this release consistent, without AWS calls.

    Search only returns photos whose index job is 'completed'. Older code
    could leave faces stored with no job row, or a job stuck in
    'processing' ("reconciliation required"). Here:
      * faces stored + job missing/unfinished  -> job 'completed' (searchable,
        and never sent to Rekognition again);
      * job stuck in 'processing' with no faces -> 'failed' (retryable from
        the admin Face Indexing page).
    Authorizations are never created here: that remains a consent decision.
    """
    conn.execute("""
        INSERT INTO photo_index_jobs
            (photo_id, collection_id, status, face_count, completed_at)
        SELECT photo_id, collection_id, 'completed', COUNT(*), CURRENT_TIMESTAMP
        FROM photo_faces
        GROUP BY photo_id, collection_id
        ON CONFLICT(photo_id, collection_id) DO UPDATE SET
            status = 'completed',
            face_count = excluded.face_count,
            completed_at = COALESCE(photo_index_jobs.completed_at, excluded.completed_at),
            error_message = NULL
        WHERE photo_index_jobs.status != 'completed'
    """)
    conn.execute("""
        UPDATE photo_index_jobs
        SET status = 'failed',
            error_message = 'Interrupted before faces were stored; safe to retry'
        WHERE status = 'processing'
          AND NOT EXISTS (
              SELECT 1 FROM photo_faces f
              WHERE f.photo_id = photo_index_jobs.photo_id
                AND f.collection_id = photo_index_jobs.collection_id
          )
    """)


MIGRATIONS: list[tuple[str, Callable[[sqlite3.Connection], None]]] = [
    ("000_baseline", _m000_baseline),
    ("001_gallery", _m001_gallery),
    ("002_accounts", _m002_accounts),
    ("003_attendee_search", _m003_attendee_search),
    ("004_indexing_and_notifications", _m004_indexing_and_notifications),
    ("005_reconcile_indexed_photos", reconcile_indexed_photos),
]


def _backup(db_path: Path) -> Path:
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    backup_path = db_path.with_name(f"{db_path.name}.pre-migrate-{stamp}.bak")
    with sqlite3.connect(db_path) as source, sqlite3.connect(backup_path) as target:
        source.backup(target)
    return backup_path


def apply(db_path: Path | str, backup: bool = True) -> Path | None:
    """Apply all pending migrations. Returns the backup path, if one was made."""
    db_path = Path(db_path)
    backup_path = None

    conn = sqlite3.connect(db_path, isolation_level=None)
    try:
        applied = _applied_versions(conn)
        pending = [(v, fn) for v, fn in MIGRATIONS if v not in applied]

        # Back up before touching anything, including schema_migrations.
        if pending and backup and _has_user_tables_besides_migrations(conn):
            conn.close()
            backup_path = _backup(db_path)
            logger.info("Database backed up to %s", backup_path)
            conn = sqlite3.connect(db_path, isolation_level=None)

        conn.execute(
            "CREATE TABLE IF NOT EXISTS schema_migrations ("
            "version TEXT PRIMARY KEY, "
            "applied_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP)"
        )

        for version, migration in pending:
            conn.execute("BEGIN IMMEDIATE")
            try:
                migration(conn)
                conn.execute(
                    "INSERT INTO schema_migrations (version) VALUES (?)",
                    (version,),
                )
                conn.execute("COMMIT")
            except sqlite3.Error:
                conn.execute("ROLLBACK")
                logger.exception("Migration %s failed; rolled back", version)
                raise
            logger.info("Applied migration %s", version)
    finally:
        conn.close()

    return backup_path


def _applied_versions(conn: sqlite3.Connection) -> set[str]:
    exists = conn.execute(
        "SELECT 1 FROM sqlite_master WHERE type = 'table' "
        "AND name = 'schema_migrations'"
    ).fetchone()
    if not exists:
        return set()
    return {row[0] for row in conn.execute("SELECT version FROM schema_migrations")}


def _has_user_tables_besides_migrations(conn: sqlite3.Connection) -> bool:
    return conn.execute(
        "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' "
        "AND name NOT LIKE 'sqlite_%' AND name != 'schema_migrations'"
    ).fetchone()[0] > 0


def dump_schema(db_path: Path | str) -> str:
    """Render the schema of a migrated database as deterministic SQL text."""
    with sqlite3.connect(db_path) as conn:
        rows = conn.execute(
            "SELECT type, name, sql FROM sqlite_master "
            "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' "
            "ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name"
        ).fetchall()
    parts = [SCHEMA_HEADER]
    for object_type, name, sql in rows:
        parts.append(f"-- {object_type}: {name}\n{sql};\n\n")
    return "".join(parts)
